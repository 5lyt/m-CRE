#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Run TF-MoDISco-lite from the .npz files generated by
Zmay_build_tfmodisco_inputs_1362.py.

Expected input arrays:
  - one-hot sequences:   (N, L, 4)
  - attributions:        (N, L, 4)
The script also accepts old-style (N, 4, L) arrays and transposes them.
"""

import argparse
import os
import numpy as np
from modiscolite.tfmodisco import TFMoDISco
from modiscolite.io import save_hdf5


def load_npz_array(path: str, preferred_keys):
    payload = np.load(path, allow_pickle=False)
    for key in preferred_keys:
        if key in payload.files:
            return payload[key]
    if len(payload.files) == 1:
        return payload[payload.files[0]]
    raise KeyError(f"Could not find any of {preferred_keys} in {path}. Available keys: {payload.files}")


def canonicalize(arr: np.ndarray, name: str) -> np.ndarray:
    arr = np.asarray(arr)
    if arr.ndim == 4 and arr.shape[-1] == 1:
        arr = np.squeeze(arr, axis=-1)
    # Accept old saved format (N, 4, L) and convert to (N, L, 4).
    if arr.ndim == 3 and arr.shape[1] == 4 and arr.shape[-1] != 4:
        arr = arr.transpose(0, 2, 1)
    if arr.ndim != 3 or arr.shape[-1] != 4:
        raise ValueError(f"{name} must have shape (N, L, 4); got {arr.shape}")
    return arr.astype(np.float32)


def parse_args():
    p = argparse.ArgumentParser(description="Run TF-MoDISco-lite for Zmay retained candidate arrays (actual N from input).")
    p.add_argument("--input-dir", required=True, help="Directory containing ohe_1362.npz and attr_1362.npz")
    p.add_argument("--ohe", default=None, help="Optional explicit one-hot .npz path")
    p.add_argument("--attr", default=None, help="Optional explicit attribution .npz path")
    p.add_argument("--output-h5", required=True, help="Output TF-MoDISco .h5 path")
    p.add_argument("--max-seqlets-per-metacluster", type=int, default=2000)
    p.add_argument("--sliding-window-size", type=int, default=20)
    p.add_argument("--flank-size", type=int, default=5)
    p.add_argument("--trim-to-window-size", type=int, default=30)
    p.add_argument("--initial-flank-to-add", type=int, default=10)
    p.add_argument("--final-flank-to-add", type=int, default=0)
    p.add_argument("--n-leiden-runs", type=int, default=2)
    p.add_argument("--target-seqlet-fdr", type=float, default=0.05, help="Use 0.05 first; try 0.1 only if too few seqlets are found")
    return p.parse_args()


def main():
    args = parse_args()
    ohe_path = args.ohe or os.path.join(args.input_dir, "ohe_1362.npz")
    attr_path = args.attr or os.path.join(args.input_dir, "attr_1362.npz")

    one_hot = canonicalize(load_npz_array(ohe_path, ["sequences", "one_hot", "ohe", "data"]), "one_hot")
    attributions = canonicalize(load_npz_array(attr_path, ["attributions", "hypothetical_contribs", "contribs", "data"]), "attributions")

    if one_hot.shape != attributions.shape:
        raise ValueError(f"Shape mismatch: one_hot={one_hot.shape}, attributions={attributions.shape}")
    if not np.isfinite(attributions).all():
        raise ValueError("Attributions contain NaN or inf.")

    mean_abs = float(np.mean(np.abs(attributions)))
    print(f"one_hot shape:      {one_hot.shape}")
    print(f"attribution shape:  {attributions.shape}")
    print(f"mean |attr|:        {mean_abs:.8g}")
    if mean_abs < 1e-8:
        raise ValueError("Attributions are almost all zero; check SHAP generation before running TF-MoDISco.")

    pos_patterns, neg_patterns = TFMoDISco(
        hypothetical_contribs=attributions,
        one_hot=one_hot,
        max_seqlets_per_metacluster=args.max_seqlets_per_metacluster,
        sliding_window_size=args.sliding_window_size,
        flank_size=args.flank_size,
        trim_to_window_size=args.trim_to_window_size,
        initial_flank_to_add=args.initial_flank_to_add,
        final_flank_to_add=args.final_flank_to_add,
        n_leiden_runs=args.n_leiden_runs,
        target_seqlet_fdr=args.target_seqlet_fdr,
        verbose=True,
    )

    os.makedirs(os.path.dirname(os.path.abspath(args.output_h5)), exist_ok=True)
    save_hdf5(args.output_h5, pos_patterns, neg_patterns, window_size=one_hot.shape[1])
    print(f"[DONE] saved TF-MoDISco results: {args.output_h5}")


if __name__ == "__main__":
    main()
